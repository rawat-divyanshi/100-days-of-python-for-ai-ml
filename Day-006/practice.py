# ----------------------------------------------------------
# Example 1: Print "Hello" 5 Times
# ----------------------------------------------------------

for i in range(5):
    print("Hello")

print()


# ----------------------------------------------------------
# Example 2: Print Numbers from 0 to 4
# ----------------------------------------------------------

for i in range(5):
    print(i)

print()


# ----------------------------------------------------------
# Example 3: Print Numbers from 1 to 5
# ----------------------------------------------------------

for i in range(1, 6):
    print(i)

print()


# ----------------------------------------------------------
# Example 4: Print Even Numbers from 2 to 10
# ----------------------------------------------------------

for i in range(2, 11, 2):
    print(i)

print()


# ----------------------------------------------------------
# Example 5: Print Odd Numbers from 1 to 9
# ----------------------------------------------------------

for i in range(1, 10, 2):
    print(i)

print()


# ----------------------------------------------------------
# Example 6: Print Your Name 5 Times
# ----------------------------------------------------------

name = input("Enter your name: ")

for i in range(5):
    print(name)

print()


# ----------------------------------------------------------
# Example 7: Print Squares of Numbers
# ----------------------------------------------------------

for i in range(1, 6):
    print(i, "Square =", i * i)

print()


# ----------------------------------------------------------
# Example 8: Multiplication Table
# ----------------------------------------------------------

number = int(input("Enter a number: "))

for i in range(1, 11):
    print(f"{number} x {i} = {number * i}")

print()


# ----------------------------------------------------------
# Example 9: Sum of First 10 Numbers
# ----------------------------------------------------------

total = 0

for i in range(1, 11):
    total += i

print("Sum =", total)

print()


# ----------------------------------------------------------
# Example 10: while Loop
# ----------------------------------------------------------

count = 1

while count <= 5:
    print(count)
    count += 1

print()


# ----------------------------------------------------------
# Example 11: Countdown
# ----------------------------------------------------------

count = 5

while count >= 1:
    print(count)
    count -= 1

print("Blast Off!")

print()


# ----------------------------------------------------------
# Example 12: break Statement
# ----------------------------------------------------------

for i in range(10):

    if i == 5:
        break

    print(i)

print()


# ----------------------------------------------------------
# Example 13: continue Statement
# ----------------------------------------------------------

for i in range(6):

    if i == 3:
        continue

    print(i)

print()


# ----------------------------------------------------------
# Example 14: pass Statement
# ----------------------------------------------------------

for i in range(5):

    if i == 2:
        pass

    print(i)

print()


# ----------------------------------------------------------
# Example 15: Simple Star Pattern
# ----------------------------------------------------------

for i in range(1, 6):
    print("*" * i)

print()


# ----------------------------------------------------------
# Example 16: Number Pattern
# ----------------------------------------------------------

for i in range(1, 6):
    print(i * str(i))

print()


# ----------------------------------------------------------
# Example 17: Reverse Counting
# ----------------------------------------------------------

for i in range(10, 0, -1):
    print(i)

print()


# ----------------------------------------------------------
# Example 18: Print Characters of a String
# ----------------------------------------------------------

text = "PYTHON"

for letter in text:
    print(letter)

print()


# ----------------------------------------------------------
# Example 19: Find Even Numbers using if
# ----------------------------------------------------------

for i in range(1, 11):

    if i % 2 == 0:
        print(i)

print()


# ----------------------------------------------------------
# Example 20: Guess Loop
# ----------------------------------------------------------

secret = 7

guess = 0

while guess != secret:

    guess = int(input("Guess the number: "))

print("Correct Guess!")

print()


